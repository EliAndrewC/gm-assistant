"""The conversion table: an era's money in goods dollars, wage dollars and Rokugani coin.

`export` writes `data/conversions.json`, which diagram's research site reads to put a conversion on
every historical amount it prints (spec 222, FR-013). It is GENERATED: a test regenerates it and
fails if the committed file differs, so it never drifts from the eras, baskets and snapshots.
Each figure is per ONE unit of the coin; a page multiplies by the amount it shows.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from l7r.money import coins
from l7r.money.basket import DATA, Basket, Model, Snapshot, convert
from l7r.money.readings import Wage

__all__ = ['TABLE', 'rokugani', 'table', 'write']

TABLE = DATA / 'conversions.json'


def rokugani(sen: float) -> str:
    """A Rokugani sum in sen, zeni, bu and/or koku; under 10 sen, to a tenth of a sen."""
    if sen < 10:
        return f'{sen:.1f} sen'
    return coins.everyday(round(sen))


def table(
    model: Model, basket: Basket, snapshot: Snapshot, koku_kg: float, wage: Wage
) -> dict[str, Any]:
    """Every era's coins at the default reading: the geometric mean over goods (central), with the
    whole basket's arithmetic reading beside it as `goods_dollars_high` (feature 223), Rokugan
    priced by every era at its weight."""
    eras: dict[str, Any] = {}
    for era in model.eras.values():
        units: dict[str, Any] = {}
        first = None
        for unit, coin in era.coins.items():
            c = convert(model, era, 1, unit, basket, snapshot, koku_kg, wage.day)
            first = first or c
            units[unit] = {
                'silver_g': round(c.silver_g, 6),
                'goods_dollars': round(c.goods_dollars, 6),
                'goods_dollars_high': round(c.goods_dollars_high, 6),
                'wage_dollars': round(c.wage_dollars, 6),
                'rokugan_sen': round(c.rokugan_sen, 6),
                'note': coin.note,
                'source': coin.source,
            }
        assert first is not None
        eras[era.id] = {
            'place': era.place,
            'years': era.years,
            'confidence': era.confidence,
            'basket_coverage': first.coverage,
            'goods_left_out': list(first.left_out),
            'wage_silver_g_per_day': era.wage_g_per_day,
            'units': units,
        }
    return {
        '_format': (
            'Generated by `python3 -m l7r.money export` (gm-assistant features 222, 223); never '
            'edit by hand. Per ONE unit of each coin: grams of pure silver; goods dollars (what it '
            "bought: the central reading, the geometric mean over the basket's goods at the "
            'snapshot, '
            'feature 223); goods_dollars_high (the same by the whole basket, the high end of the '
            'range); wage dollars (the same share of an unskilled day '
            "there, at a US unskilled day's pay); and rokugan_sen (what it bought, in Rokugan's "
            'coin: 10 sen a zeni, 10 zeni a bu, 10 bu a koku). Multiply by the amount shown.'
        ),
        'basket': basket.id,
        'mean': 'geometric',
        'snapshot': snapshot.date,
        'koku_kg': round(koku_kg, 3),
        'us_wage': {'date': wage.date, 'hourly': wage.hourly, 'day': round(wage.day, 2)},
        'eras': eras,
    }


def write(data: dict[str, Any], path: Path = TABLE) -> Path:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n')
    return path
